def set_language(language: str | None) -> None:
    global _current
    _current = language if language in LANGUAGES else DEFAULT_LANGUAGE


def t(key: str, **kwargs: Any) -> str:
    table = _TRANSLATIONS.get(_current, {})
    text = table.get(key) or _TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text
